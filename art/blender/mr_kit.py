"""Magnet Rush — shared Blender authoring kit.

Every runtime asset in this game is generated by script, headlessly, so the
art pipeline is reproducible and reviewable in version control rather than
living inside binary .blend files.

Run through Blender, never through a bare Python interpreter:

    blender --background --python art/blender/build_assets.py

Conventions enforced here (see docs/blender_pipeline.md):

  * metric scale, 1 Blender unit = 1 metre
  * +Y up, -Z forward at export (glTF convention; the exporter converts)
  * transforms applied, origin at the logical pivot
  * flat shading — the art bible calls for faceted, crystalline geometry
  * a small set of shared materials, so draw calls stay low
"""

