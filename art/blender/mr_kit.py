def torus(name, major=1.0, minor=0.15, major_seg=16, minor_seg=6, at=(0, 0, 0),
          mat=None):
    """A low-poly ring — used for the Core's magnetic rings."""
    bm = new_bmesh()
    for i in range(major_seg):
        a = (i / major_seg) * math.tau
        center = Vector((math.cos(a) * major, math.sin(a) * major, 0.0))
        radial = Vector((math.cos(a), math.sin(a), 0.0))
        ring = []
        for j in range(minor_seg):
            b = (j / minor_seg) * math.tau
            offset = radial * (math.cos(b) * minor) + Vector(
                (0, 0, math.sin(b) * minor)
            )
            ring.append(bm.verts.new(center + offset))
        bm.verts.ensure_lookup_table()
    bm.verts.ensure_lookup_table()
    verts = bm.verts[:]
    for i in range(major_seg):
        for j in range(minor_seg):
            a0 = verts[i * minor_seg + j]
            a1 = verts[i * minor_seg + (j + 1) % minor_seg]
            b0 = verts[((i + 1) % major_seg) * minor_seg + j]
            b1 = verts[((i + 1) % major_seg) * minor_seg + (j + 1) % minor_seg]
            bm.faces.new((a0, a1, b1, b0))
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bmesh.ops.translate(bm, vec=Vector(at), verts=bm.verts)
    obj = from_bmesh(bm, name)
    flat_shade(obj)
    if mat:
        assign(obj, mat)
    return obj


def gear(name, teeth=10, inner=0.28, root=0.42, tip=0.58, thickness=0.14,
         at=(0, 0, 0), mat=None):
    """A chunky low-poly gear. Reads clearly at swarm scale."""
    bm = new_bmesh()
    half = thickness * 0.5
    rings_bottom, rings_top = [], []
    step = math.tau / (teeth * 2)
    for i in range(teeth * 2):
        a = i * step
        r = tip if (i % 2 == 0) else root
        rings_bottom.append(bm.verts.new((math.cos(a) * r, math.sin(a) * r, -half)))
        rings_top.append(bm.verts.new((math.cos(a) * r, math.sin(a) * r, half)))
    hub_bottom, hub_top = [], []
    for i in range(teeth * 2):
        a = i * step
        hub_bottom.append(
            bm.verts.new((math.cos(a) * inner, math.sin(a) * inner, -half))
        )
        hub_top.append(bm.verts.new((math.cos(a) * inner, math.sin(a) * inner, half)))

    n = teeth * 2
    for i in range(n):
        j = (i + 1) % n
        bm.faces.new((rings_bottom[i], rings_bottom[j], rings_top[j], rings_top[i]))
        bm.faces.new((hub_top[i], hub_top[j], hub_bottom[j], hub_bottom[i]))
        bm.faces.new((hub_top[i], rings_top[i], rings_top[j], hub_top[j]))
        bm.faces.new((rings_bottom[i], hub_bottom[i], hub_bottom[j], rings_bottom[j]))

    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bmesh.ops.translate(bm, vec=Vector(at), verts=bm.verts)
    obj = from_bmesh(bm, name)
    flat_shade(obj)
    if mat:
        assign(obj, mat)
    return obj


def crystal(name, radius=1.0, subdiv=1, jitter=0.22, seed=1, at=(0, 0, 0),
            mat=None):
    """A faceted energy crystal: an icosphere pushed off-sphere per vertex.

    This is the Kanban Core silhouette — angular, asymmetrical but balanced.
    """
    rng = random.Random(seed)
    bm = new_bmesh()
    bmesh.ops.create_icosphere(bm, subdivisions=subdiv, radius=radius)
    for v in bm.verts:
        v.co *= 1.0 + rng.uniform(-jitter, jitter)
    bmesh.ops.translate(bm, vec=Vector(at), verts=bm.verts)
    obj = from_bmesh(bm, name)
    flat_shade(obj)
    if mat:
        assign(obj, mat)
    return obj


def bevel_plate(name, sx, sy, sz, cut=0.06, at=(0, 0, 0), mat=None):
    """A chamfered slab — the platform/armour building block."""
    bm = new_bmesh()
    bmesh.ops.create_cube(bm, size=1.0)
    bmesh.ops.scale(bm, vec=Vector((sx, sy, sz)), verts=bm.verts)
    bmesh.ops.bevel(
        bm,
        geom=list(bm.verts) + list(bm.edges) + list(bm.faces),
        offset=cut,
        segments=1,
        affect="EDGES",
    )
    bmesh.ops.translate(bm, vec=Vector(at), verts=bm.verts)
    obj = from_bmesh(bm, name)
    flat_shade(obj)
    if mat:
        assign(obj, mat)
    return obj


