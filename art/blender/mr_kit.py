def triangle_count(obj: bpy.types.Object) -> int:
    total = 0
    for poly in obj.data.polygons:
        total += max(0, len(poly.vertices) - 2)
    return total


def export_glb(obj: bpy.types.Object, out_path: str) -> dict:
    """Exports one object as GLB and returns its manifest record."""
    os.makedirs(os.path.dirname(out_path), exist_ok=True)

    recalc_normals(obj)
    apply_transforms(obj)

    for o in bpy.context.scene.objects:
        o.select_set(False)
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj

    bpy.ops.export_scene.gltf(
        filepath=out_path,
        export_format="GLB",
        use_selection=True,
        export_apply=True,
        export_yup=True,
        export_normals=True,
        export_materials="EXPORT",
        export_cameras=False,
        export_lights=False,
    )

    tris = triangle_count(obj)
    return {
        "name": obj.name,
        "glb": out_path.replace("\\", "/"),
        "triangles": tris,
        "materials": len([m for m in obj.data.materials if m is not None]),
        "bytes": os.path.getsize(out_path) if os.path.exists(out_path) else 0,
    }


def write_manifest(records: list[dict], path: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(records, fh, indent=2)
