def reset_scene() -> None:
    """Wipes the file back to an empty metric scene."""
    bpy.ops.wm.read_factory_settings(use_empty=True)
    # Reloading the file invalidates every cached datablock, so the material
    # cache must go with it or lookups hit a dead StructRNA.
    _material_cache.clear()
    scene = bpy.context.scene
    scene.unit_settings.system = "METRIC"
    scene.unit_settings.scale_length = 1.0


def _link(obj: bpy.types.Object) -> None:
    bpy.context.collection.objects.link(obj)


# ---------------------------------------------------------------------------
# Materials
# ---------------------------------------------------------------------------

_material_cache: dict[str, bpy.types.Material] = {}


def material(
    name: str,
    color=SILVER,
    *,
    metallic: float = 0.9,
    roughness: float = 0.35,
    emission=None,
    emission_strength: float = 0.0,
    alpha: float = 1.0,
) -> bpy.types.Material:
    """A Principled BSDF material. Cached, so assets share materials."""
    key = f"{name}"
    hit = _material_cache.get(key)
    if hit is not None:
        try:
            if hit.name in bpy.data.materials:
                return hit
        except ReferenceError:
            # Datablock was freed underneath us; fall through and rebuild.
            _material_cache.pop(key, None)

    mat = bpy.data.materials.new(name=name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = (*color, 1.0)
    bsdf.inputs["Metallic"].default_value = metallic
    bsdf.inputs["Roughness"].default_value = roughness
    if alpha < 1.0:
        bsdf.inputs["Alpha"].default_value = alpha
        mat.blend_method = "BLEND"
    if emission is not None:
        bsdf.inputs["Emission Color"].default_value = (*emission, 1.0)
        bsdf.inputs["Emission Strength"].default_value = emission_strength
    _material_cache[key] = mat
    return mat


def assign(obj: bpy.types.Object, mat: bpy.types.Material) -> bpy.types.Object:
    obj.data.materials.clear()
    obj.data.materials.append(mat)
    return obj


# ---------------------------------------------------------------------------
# Mesh construction
# ---------------------------------------------------------------------------


def from_bmesh(bm: bmesh.types.BMesh, name: str) -> bpy.types.Object:
    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()
    obj = bpy.data.objects.new(name, mesh)
    _link(obj)
    return obj


def new_bmesh() -> bmesh.types.BMesh:
    return bmesh.new()


def flat_shade(obj: bpy.types.Object) -> bpy.types.Object:
    """Faceted look. The art bible is explicit about this."""
    for poly in obj.data.polygons:
        poly.use_smooth = False
    return obj


def smooth_shade(obj: bpy.types.Object) -> bpy.types.Object:
    for poly in obj.data.polygons:
        poly.use_smooth = True
    return obj


def recalc_normals(obj: bpy.types.Object) -> bpy.types.Object:
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(obj.data)
    bm.free()
    obj.data.update()
    return obj


def apply_transforms(obj: bpy.types.Object) -> bpy.types.Object:
    """Bakes loc/rot/scale into the mesh so the runtime gets clean data."""
    obj.data.transform(obj.matrix_world)
    obj.matrix_world = Matrix.Identity(4)
    return obj


def join(objs: list[bpy.types.Object], name: str) -> bpy.types.Object:
    """Merges objects into one mesh, preserving per-face materials."""
    assert objs, "join() needs at least one object"
    target = bpy.data.meshes.new(name)
    bm = bmesh.new()
    mat_index: dict[str, int] = {}
    materials: list[bpy.types.Material] = []

    for obj in objs:
        apply_transforms(obj)
        for slot in obj.data.materials:
            if slot is not None and slot.name not in mat_index:
                mat_index[slot.name] = len(materials)
                materials.append(slot)

    for obj in objs:
        tmp = bmesh.new()
        tmp.from_mesh(obj.data)
        remap = {}
        for i, slot in enumerate(obj.data.materials):
            remap[i] = mat_index.get(slot.name, 0) if slot else 0
        for face in tmp.faces:
            face.material_index = remap.get(face.material_index, 0)
        merged = bpy.data.meshes.new(f"__tmp_{obj.name}")
        tmp.to_mesh(merged)
        tmp.free()
        bm.from_mesh(merged)
        bpy.data.meshes.remove(merged)

    bm.to_mesh(target)
    bm.free()

    out = bpy.data.objects.new(name, target)
    for mat in materials:
        out.data.materials.append(mat)
    _link(out)

    for obj in objs:
        bpy.data.objects.remove(obj, do_unlink=True)
    return out


